; =====================================================================
; SPC700 最小発音テストコード（構文修正版）
; =====================================================================

    org $0200               ; プログラムの配置開始アドレス

Main:
    clrc                    ; 初期化

    ; --- DSPの初期化 ---
    mov   $F2, #$6C          ; DSP アドレスレジスタ($F2) に $6C (FLG) を指定
    mov   $F3, #$00          ; DSP データレジスタ($F3) に $00 を書き込み (ミュート解除)

    ; --- サンプルディレクトリ (DIR) の設定 ---
    ; テーブルを $1000 に配置するため、$1000 / 256 = $10 を設定
    mov   $F2, #$5D          ; DIR レジスタ
    mov   $F3, #$10

    ; --- チャンネル0 (Vo0) の音量・ピッチ・波形指定 ---
    mov   $F2, #$00          ; VOL L (左音量)
    mov   $F3, #$7F          
    
    mov   $F2, #$01          ; VOL R (右音量)
    mov   $F3, #$7F

    mov   $F2, #$02          ; P_L (ピッチ下位)
    mov   $F3, #$00          
    
    mov   $F2, #$03          ; P_H (ピッチ上位)
    mov   $F3, #$10          ; ピッチ設定 ($1000)

    mov   $F2, #$04          ; SRN (サンプル番号)
    mov   $F3, #$00          ; 0番目の音（MyWaveform）を指定

    mov   $F2, #$05          ; ADSR1
    mov   $F3, #$FF          ; 直ちに最大音量
    
    mov   $F2, #$06          ; ADSR2
    mov   $F3, #$E0          ; サスティン維持

    ; --- キーオン (発音開始) ---
    mov   $F2, #$4C          ; KON (キーオンレジスタ)
    mov   $F3, #$01          ; チャンネル0 をオン

Loop:
    bra   Loop               ; 無限ループで発音を維持


; =====================================================================
; データ領域 (テーブルとBRR波形)
; =====================================================================

    org $1000
DirTable:
    dw    MyWaveform         ; 発音開始アドレス
    dw    MyWaveform         ; ループ先アドレス

    org $1110
MyWaveform:
    ; BRR 1ブロック（9バイト）
    db    $05                ; フィルター0、シフト0、LOOP=1, END=0
    db    $77, $77, $77, $77 ; 波形データ（前半）
    db    $88, $88, $88, $88 ; 波形データ（後半）
